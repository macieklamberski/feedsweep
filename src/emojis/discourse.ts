// A toned file is named by its Fitzpatrick type, 2 to 6, inside a folder named for the emoji.
const toneRegex = /^[2-6]$/

const getNameGlyph = (name: string): string | undefined => {
  return discourseNames.get(name) ?? glyphFromGemojiName(name)
}

// See: https://github.com/discourse/discourse/blob/main/app/models/emoji.rb, for the tone.
const getGlyph = (src: string): string | undefined => {
  const path = src.split(queryOrHashRegex)[0]
  const stem = getFileStem(path)
  const isToned = toneRegex.test(stem)
  const name = isToned ? getFileStem(path.slice(0, path.lastIndexOf('/'))) : stem
  const glyph = getNameGlyph(discourseAliases.get(name) ?? name)

  if (!glyph || !isToned) {
    return glyph
  }

  // Type 2 is the first modifier, which applyTones numbers 1, and every person takes the tone.
  return applyTones(glyph, `${Number(stem) - 1}`)
}

// Discourse's stock emoji, named by the shortcode Discourse writes, a gemoji name or its own.
export const discourseEmojiResolver: EmojiResolver = {
  kind: 'emoji',
  selector: sets
    .flatMap((set) => {
      return [
        `img[class~="emoji" i][src*="/images/emoji/${set}/" i]`,
        `img[src*="emoji.discourse-cdn.com/${set}/" i]`, // Discourse's own CDN, on hosted sites
      ]
    })
    .join(', '),
  extract: (element) => {
    const src = element.getAttribute('src') ?? ''
    const glyph = getGlyph(src)

    // gemoji's own images sit under `/images/emoji/unicode/` too, named by codepoint, which no
    // Discourse set writes. The generic `emoji` class resolver converts those.
    if (!glyph && glyphFromCodepoints(getFileStem(src.split(queryOrHashRegex)[0]))) {
      return
    }

    return resolveEmojiImage(element, { isStrong: true, glyph })
  },
}
